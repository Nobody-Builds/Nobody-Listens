"""Convert the Nobody Listens traced SVG masters into Android VectorDrawables (square viewport, art centred).

usage (from the repo root): python tools/svg2vd.py ../sub-brands/nobody-listens/logo/svg shared/src/main/res/drawable
"""
import re
import sys
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])
HEAD = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/svg2vd.py from the Nobody Listens logo kit ({src}); do not edit by hand. -->\n'


def compact(d):
    """Integer coordinates and relative curves: aapt2 stores strings with a 15-bit length, so a pathData over 32767
    characters is corrupted. Rounding absolute points first keeps the relative steps from drifting."""
    out, cur, start = [], (0, 0), (0, 0)
    for cmd, args in re.findall(r"([MCZ])([^MCZ]*)", d):
        n = [round(float(v)) for v in re.findall(r"-?\d*\.?\d+", args)]
        if cmd == "M":
            cur = start = (n[0], n[1])
            out.append(f"M{n[0]} {n[1]}")
        elif cmd == "C":
            for i in range(0, len(n), 6):
                x1, y1, x2, y2, x, y = n[i:i + 6]
                px, py = cur
                out.append("c" + " ".join(str(v) for v in (x1 - px, y1 - py, x2 - px, y2 - py, x - px, y - py)))
                cur = (x, y)
        else:
            out.append("Z")
            cur = start
    return re.sub(r" -", "-", "".join(out))


def convert(svg_name, out_name, size_dp, colour=None):
    s = (src / svg_name).read_text(encoding="utf-8")
    vx, vy, vw, vh = map(float, re.findall(r'viewBox="([^"]+)"', s)[-1].split())
    side = max(vw, vh)
    ox, oy = -vx + (side - vw) / 2, -vy + (side - vh) / 2
    groups = []
    for p in re.findall(r"<path [^>]*/>", s):
        d = compact(re.search(r' d="([^"]+)"', p).group(1))
        assert len(d) < 32000, f"{svg_name}: pathData still {len(d)} chars"
        fill = colour or re.search(r'fill="(#[0-9A-Fa-f]{6})"', p).group(1).upper()
        t = re.search(r'transform="translate\(([-\d.]+),([-\d.]+)\)"', p)
        tx, ty = (float(t.group(1)), float(t.group(2))) if t else (0.0, 0.0)
        groups.append(f'        <group android:translateX="{tx:g}" android:translateY="{ty:g}">\n'
                      f'            <path android:fillColor="{fill}" android:pathData="{d}" />\n'
                      f'        </group>')
    body = "\n".join(groups)
    (out / out_name).write_text(
        HEAD.format(src=svg_name) +
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size_dp}dp"\n    android:height="{size_dp}dp"\n'
        f'    android:viewportWidth="{side:g}"\n    android:viewportHeight="{side:g}">\n'
        f'    <group android:translateX="{ox:g}" android:translateY="{oy:g}">\n{body}\n    </group>\n</vector>\n',
        encoding="utf-8", newline="\n")


convert("nobody-listens-mark.svg", "nl_mark.xml", 108)
convert("nobody-listens-mono-black.svg", "nl_mark_mono.xml", 24, "#FFFFFFFF")
